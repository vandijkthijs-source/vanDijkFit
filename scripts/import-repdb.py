"""Import RepDB's free catalog and offline illustrations for use inside vDstrong.

Run from the repo root: python3 scripts/import-repdb.py [downloaded-exercises.json]
Requires only Python's standard library. Never downloads paid preview animations.
"""

import hashlib
import json
import re
import sys
import time
import urllib.request
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
BASE_URL = "https://exercise-dataset.com/"
DATA_DIR = ROOT / "data/repdb"
IMAGE_DIR = ROOT / "assets/exercises/repdb"


def fetch(url):
    with urllib.request.urlopen(url, timeout=45) as response:
        return response.read()


def download_image(path):
    if not re.fullmatch(r"images/flat/[a-z0-9-]+\.webp", path):
        raise ValueError(f"Unexpected free image path: {path}")
    target = IMAGE_DIR / Path(path).name
    if target.exists() and target.read_bytes()[:4] == b"RIFF":
        return target.stat().st_size
    for attempt in range(3):
        try:
            content = fetch(BASE_URL + path)
            if content[:4] != b"RIFF" or content[8:12] != b"WEBP":
                raise ValueError(f"Not a WebP image: {path}")
            target.write_bytes(content)
            return len(content)
        except Exception:
            if attempt == 2:
                raise
            time.sleep(attempt + 1)


def main():
    raw = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else fetch(BASE_URL + "exercises.json")
    source = json.loads(raw)
    exercises = source["exercises"]
    ids = [exercise["id"] for exercise in exercises]
    if len(set(ids)) != len(ids):
        raise ValueError("Duplicate source exercise IDs")
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    IMAGE_DIR.mkdir(parents=True, exist_ok=True)

    catalog = []
    registry = [
        '// Generated by scripts/import-repdb.py. Exercise data by RepDB (https://repdb.co).',
        'export type RepDbImage = { source: number; label: string };',
        'export const repDbImages: Record<string, RepDbImage[]> = {',
    ]
    paths = set()
    for exercise in exercises:
        if not re.fullmatch(r"[a-z0-9-]+", exercise["id"]):
            raise ValueError("Unexpected exercise ID")
        catalog.append({
            "id": exercise["id"],
            "name": exercise["name_en"],
            "equipment": exercise.get("equipment", "bodyweight"),
            "primaryMuscles": exercise["primary_muscles"],
            "secondaryMuscles": exercise.get("secondary_muscles", []),
            "category": exercise["category"],
            "mechanic": exercise.get("mechanic", "isolation"),
        })
        registry.append(f'  {json.dumps(exercise["id"])}: [')
        images = exercise["images"]["flat"]
        for pose, label in [("main", "Position"), ("start", "Start"), ("peak", "Finish")]:
            if pose not in images:
                continue
            path = images[pose]
            paths.add(path)
            registry.append(
                '    { source: require("../../assets/exercises/repdb/'
                + Path(path).name + '"), label: ' + json.dumps(label) + ' },'
            )
        registry.append('  ],')
    registry.append('};')

    total_bytes = 0
    with ThreadPoolExecutor(max_workers=6) as pool:
        futures = [pool.submit(download_image, path) for path in sorted(paths)]
        for count, future in enumerate(as_completed(futures), start=1):
            total_bytes += future.result()
            if count % 100 == 0:
                print(f"Downloaded/verified {count}/{len(paths)} images", flush=True)

    (DATA_DIR / "catalog.json").write_text(json.dumps(catalog, indent=2) + "\n")
    (DATA_DIR / "images.ts").write_text("\n".join(registry) + "\n")
    (DATA_DIR / "LICENSE-DATA.md").write_bytes(fetch(
        "https://raw.githubusercontent.com/RepDB/exercise-dataset/main/LICENSE-DATA.md"
    ))
    (DATA_DIR / "source.json").write_text(json.dumps({
        "url": BASE_URL + "exercises.json",
        "sha256": hashlib.sha256(raw).hexdigest(),
        "schemaVersion": source["schema_version"],
        "exerciseCount": len(exercises),
        "imageCount": len(paths),
    }, indent=2) + "\n")
    print(f"Imported {len(exercises)} exercises, {len(paths)} images ({total_bytes / 1024**2:.1f} MiB)")


if __name__ == "__main__":
    main()
